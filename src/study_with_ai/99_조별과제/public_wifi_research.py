def print_md(data, rows=None, title=None):
    if title:
        print()
        print("=" * 80)
        print(f"[ {title} ]")
        print("=" * 80)

    # DataFrame
    if isinstance(data, pd.DataFrame):
        if rows is not None:
            data = data.head(rows)

        print(data.to_markdown(index=False))

    # Series
    elif isinstance(data, pd.Series):
        if rows is not None:
            data = data.head(rows)

        print(data.to_frame().to_markdown())

    # ndarray, StringArray, list 등
    else:
        data = pd.Series(data, name="값")

        if rows is not None:
            data = data.head(rows)

        print(data.to_frame().to_markdown(index=False))

    print("\r\n")


